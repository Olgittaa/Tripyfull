CREATE TABLE public.places (
    id uuid NOT NULL,
    address character varying(255),
    city character varying(255),
    country character varying(2),
    created_at timestamp(6) with time zone,
    description character varying(2000),
    latitude numeric(10,7),
    longitude numeric(10,7),
    name character varying(255) NOT NULL,
    osm_id character varying(255),
    source character varying(16) NOT NULL,
    type character varying(32),
    visibility character varying(16) NOT NULL,
    owner_id bigint NOT NULL,
    CONSTRAINT places_type_check CHECK (((type)::text = ANY (ARRAY[('SIGHTSEEING'::character varying)::text, ('BEACH'::character varying)::text, ('NATURE'::character varying)::text, ('RESTAURANT'::character varying)::text, ('MUSEUM'::character varying)::text, ('VIEWPOINT'::character varying)::text, ('PORT'::character varying)::text, ('AIRPORT'::character varying)::text, ('NEIGHBORHOOD'::character varying)::text, ('PARK'::character varying)::text, ('SHOP'::character varying)::text, ('OTHER'::character varying)::text]))),
    CONSTRAINT places_visibility_check CHECK (((visibility)::text = ANY ((ARRAY['PUBLIC'::character varying, 'PRIVATE'::character varying])::text[])))
);

CREATE TABLE public.trips (
    id uuid NOT NULL,
    base_currency character varying(3),
    cover_image character varying(500),
    destination character varying(255),
    end_date date,
