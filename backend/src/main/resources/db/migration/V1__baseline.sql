
-- Baseline schema, captured from the live dev database on 2026-08-10 (pg_dump 16, schema-only).
-- Existing databases are baselined past this migration (spring.flyway.baseline-on-migrate=true);
-- fresh databases get the full schema from here. Geo reference data (countries/cities) is
-- seeded by GeoDataSeeder on startup, not by migrations.

CREATE TABLE public.activities (
    id uuid NOT NULL,
    address character varying(255),
    cost_currency character varying(3),
    cost_estimate numeric(10,2),
    end_time time(0) without time zone,
    name character varying(255) NOT NULL,
    notes character varying(2000),
    order_index integer NOT NULL,
    start_time time(0) without time zone,
    type character varying(255),
    day_id uuid NOT NULL,
    place_id uuid,
    travel_mode_to_next character varying(8),
    CONSTRAINT activities_type_check CHECK (((type)::text = ANY ((ARRAY['SIGHTSEEING'::character varying, 'BEACH'::character varying, 'NATURE'::character varying, 'NEIGHBORHOOD'::character varying, 'RESTAURANT'::character varying, 'MEAL_STOP'::character varying, 'SHOPPING'::character varying, 'TRANSPORT'::character varying, 'OTHER'::character varying])::text[])))
);

CREATE TABLE public.attachments (
    id uuid NOT NULL,
    content_type character varying(255),
    file_name character varying(255) NOT NULL,
    size bigint NOT NULL,
    storage_key character varying(255) NOT NULL,
    uploaded_at timestamp(6) with time zone NOT NULL,
    booking_id uuid NOT NULL
);

CREATE TABLE public.bookings (
    id uuid NOT NULL,
    accommodation_city character varying(255),
    address character varying(500),
    arrival_at timestamp(6) without time zone,
    arrival_terminal character varying(255),
    booking_url character varying(500),
    cabin character varying(255),
    car_class character varying(255),
    category character varying(255),
    check_in date,
    check_in_time time(0) without time zone,
    check_out date,
    check_out_time time(0) without time zone,
    confirmation_number character varying(255),
    departure_at timestamp(6) without time zone,
    departure_terminal character varying(255),
    exchange_rate numeric(12,6),
    flight_number character varying(255),
    from_iata character varying(8),
    from_place character varying(255),
    full_price numeric(10,2),
    guests integer,
    latitude double precision,
    linked_day_id uuid,
    longitude double precision,
    name character varying(255) NOT NULL,
    notes character varying(2000),
    paid_simple boolean NOT NULL,
    price_currency character varying(3),
    room_type character varying(255),
    seat character varying(255),
    to_iata character varying(8),
    to_place character varying(255),
    transport_mode character varying(255),
    vendor character varying(255),
    vessel_name character varying(255),
    trip_id uuid NOT NULL,
    CONSTRAINT bookings_category_check CHECK (((category)::text = ANY ((ARRAY['TRANSPORTATION'::character varying, 'ACCOMMODATION'::character varying, 'ACTIVITY'::character varying])::text[]))),
    CONSTRAINT bookings_transport_mode_check CHECK (((transport_mode)::text = ANY ((ARRAY['FLIGHT'::character varying, 'FERRY'::character varying, 'BUS'::character varying, 'METRO'::character varying, 'CAR_RENTAL'::character varying, 'TAXI'::character varying, 'WALK'::character varying])::text[])))
);

CREATE TABLE public.cities (
    id bigint NOT NULL,
    latitude double precision,
    longitude double precision,
    name character varying(255) NOT NULL,
    popular boolean NOT NULL,
    country_code character varying(2) NOT NULL
);

ALTER TABLE public.cities ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.cities_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE public.countries (
    code character varying(2) NOT NULL,
    name character varying(255) NOT NULL,
    region character varying(255)
);

CREATE TABLE public.days (
    id uuid NOT NULL,
    city character varying(255),
    date date NOT NULL,
    linked_booking_id uuid,
    notes character varying(1000),
    overnight_stay character varying(255),
    trip_id uuid NOT NULL
);

CREATE TABLE public.expenses (
    id uuid NOT NULL,
    amount numeric(10,2) NOT NULL,
    category character varying(255),
    currency character varying(3),
    description character varying(255),
    spent_at timestamp(6) without time zone,
    day_id uuid NOT NULL,
    CONSTRAINT expenses_category_check CHECK (((category)::text = ANY ((ARRAY['FOOD'::character varying, 'TRANSPORT'::character varying, 'ACTIVITY'::character varying, 'ACCOMMODATION'::character varying, 'OTHER'::character varying])::text[])))
);

CREATE TABLE public.folder_places (
    folder_id uuid NOT NULL,
    place_id uuid NOT NULL
);

CREATE TABLE public.payments (
    id uuid NOT NULL,
    amount numeric(10,2) NOT NULL,
    due_date date,
    paid boolean NOT NULL,
    paid_date date,
    sequence integer NOT NULL,
    booking_id uuid NOT NULL
);

CREATE TABLE public.place_folders (
    id uuid NOT NULL,
    color character varying(255),
    created_at timestamp(6) with time zone NOT NULL,
    name character varying(255) NOT NULL,
    owner_id bigint NOT NULL
