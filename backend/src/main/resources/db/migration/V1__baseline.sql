    owner_id bigint NOT NULL,
    CONSTRAINT trips_status_check CHECK (((status)::text = ANY ((ARRAY['DRAFT'::character varying, 'PLANNED'::character varying, 'ACTIVE'::character varying, 'COMPLETED'::character varying])::text[])))
);

